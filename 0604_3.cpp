#include <bits/stdc++.h>
using namespace std;

int main() {
    int n, m;
    cin >> n >> m;
    int i = 0, j = 0;
    cout << "A:";
    while (i < n) {
        cout << "]";
        i++;
    }
    cout << endl;
    cout << "B:";
    while (j < m) {
        cout << "]";
        j++;
    }
    cout << endl;
}